const LED_COLORS_DE = {red: 'rot', green: 'grün', yellow: 'gelb', blue: 'blau', white: 'weiß', orange: 'orange'};

/** Palette text in `lang`: German from the table, English otherwise or when missing. */
export const paletteText = (text, lang) => (lang === 'de' && text && PALETTE_DE[text]) || text;

export const paletteUi = (key, lang, vars) => {
  const entry = PALETTE_UI[key] || {};
  let s = (lang === 'de' && entry.de) || entry.en || key;
  for (const [k, v] of Object.entries(vars || {})) s = s.replace(`{${k}}`, String(v));
  return s;
};

export const ledColorName = (color, lang) => (lang === 'de' && LED_COLORS_DE[color]) || color;
